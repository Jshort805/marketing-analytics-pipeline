import numpy as np
import pandas as pd
import plotly.express as px
import streamlit as st

from utils import have, load, load_json, md, money, note, setup

setup("Data trust", "✅")
st.title("Data trust: can I believe these numbers?")
st.caption("Every figure in this app passes through the pipeline below. This page shows its health, reconciles the totals, and states the limits.")

meta = load_json("pipeline_meta")
orders, tp, cp, spend = load("orders"), load("touchpoints"), load("channel_performance"), load("daily_spend")

note("This is synthetic data generated by scripts/generate_data.py (seeded, with injected duplicates and missing touchpoints to mimic real-world mess). "
     "The pipeline and methods are real; the business is not.", "warning")

md("##### Pipeline")
st.graphviz_chart("""digraph { rankdir=LR; node [shape=box, style="rounded,filled", fillcolor="#eef2f8", color="#9aa7bd", fontname="Helvetica"];
 raw [label="raw tables\\n(loaded to DuckDB)"]; stg [label="staging\\ncleaned and typed"]; int [label="intermediate\\nattribution joins"];
 marts [label="marts\\nfct_ and dim_ tables"]; ml [label="models\\nBG/NBD, MMM"]; app [label="this app\\nparquet files", fillcolor="#dbe8fb"];
 raw -> stg -> int -> marts -> ml -> app; marts -> app }""")

c = st.columns(4)
c[0].metric("Orders", f"{meta['orders']:,}")
c[1].metric("Customers", f"{meta['customers']:,}")
c[2].metric("Data window", f"{meta['data_start']} to {meta['data_end']}")
c[3].metric("Last refresh", meta["generated_at"])

if have("dbt_results"):
    r = load("dbt_results")
    tests = r[r["resource_type"] == "test"]
    ok = (tests["status"] == "pass").sum()
    md("##### dbt build results")
    a, b, c3 = st.columns(3)
    a.metric("Tests passing", f"{ok} of {len(tests)}")
    b.metric("Models built", f"{(r['resource_type'] == 'model').sum()}")
    c3.metric("Total build time", f"{r['seconds'].sum():.1f}s")
    s = r.groupby(["resource_type", "status"]).size().reset_index(name="count")
    fig = px.bar(s, x="resource_type", y="count", color="status", title="Build outcome by resource type",
                 color_discrete_map={"pass": "#3a9a5b", "success": "#3a9a5b", "warn": "#e0a21e", "error": "#d6453a", "fail": "#d6453a"})
    fig.update_layout(height=300, margin=dict(t=40))
    st.plotly_chart(fig, width='stretch')
    with st.expander("Every model and test"):
        st.dataframe(r[["resource_type", "name", "status", "seconds"]], hide_index=True, width='stretch')
else:
    st.info("Run `dbt build` and then the export script to show test results here.")

md("##### Reconciliation checks (computed live from the exported data)")
w = tp.groupby("order_id")[["first_touch_weight", "last_touch_weight", "linear_weight"]].sum()
bad = int((np.abs(w - 1) > 1e-6).any(axis=1).sum())
dark = orders["is_dark_order"].mean()
attr_rev = tp.drop_duplicates("order_id")["revenue"].sum()
tot_rev = orders["revenue"].sum()
dark_rev = orders.loc[orders["is_dark_order"], "revenue"].sum()
cp_rev = cp["last_touch_revenue"].sum() if "last_touch_revenue" in cp else np.nan
checks = pd.DataFrame([
    ("Attribution weights sum to 1 for every order (first, last, linear)", bad == 0, f"{bad} orders off"),
    ("Order IDs are unique in the orders mart", orders["order_id"].is_unique, f"{len(orders):,} rows"),
    ("Attributed revenue + dark-order revenue = total revenue", abs(attr_rev + dark_rev - tot_rev) < 1,
     f"{money(attr_rev)} + {money(dark_rev)} vs {money(tot_rev)}"),
    ("Channel mart last-touch revenue matches touchpoint-level total", (abs(cp_rev - attr_rev) < 1) if cp_rev == cp_rev else True,
     f"{money(cp_rev)} vs {money(attr_rev)}"),
    ("No negative spend or revenue", bool((spend["spend"] >= 0).all() and (orders["revenue"] >= 0).all()), "checked"),
], columns=["check", "passed", "detail"])
checks["result"] = np.where(checks["passed"], "PASS", "REVIEW")
st.dataframe(checks[["result", "check", "detail"]], hide_index=True, width='stretch')
note(f"{dark:.1%} of orders ({money(dark_rev)} of revenue) have no tracked touchpoint. They are in the revenue totals but cannot be credited to a channel, "
     "which is why attribution tables on other pages sum to less than total revenue.")

md("##### Table sizes")
tb = pd.DataFrame(meta["table_rows"].items(), columns=["table", "rows"]).sort_values("rows")
fig = px.bar(tb, x="rows", y="table", orientation="h", log_x=True)
fig.update_layout(height=max(320, 22 * len(tb)), margin=dict(t=10), yaxis_title=None)
st.plotly_chart(fig, width='stretch')

md("##### Limits to keep in mind")
md("""- **Correlation, not causation.** Attribution splits credit among touches that happened; it does not prove a channel caused the sale. The MMM is also observational.
- **Little history.** About two years of weekly data supports a coarse MMM. Treat channel returns as a ranking with a band.
- **Lifetime value is a forecast.** BG/NBD assumes customers do not change behavior; the out-of-sample check on the Customers page shows how well it held up.
- **Spend is not split by country or device**, so ROAS is only shown for all-market views.
- **Next steps that would make this production-grade:** run lift tests to calibrate the MMM, schedule the pipeline (Airflow DAG is in the repo), and point the app at the warehouse instead of exported files.""")
